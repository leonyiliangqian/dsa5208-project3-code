#!/usr/bin/env python3
"""Generate the report's scaling figures and tables from analysed runs.

Input: one or more summary.json files written by analyze.py (each lists the
run directories it was built from). Output: LaTeX fragments (pgfplots
figures and tables) for main.tex to \\input; no number is typed by hand.

  report_figures.py SUMMARY.json [...] [--out DIR] [--allow-local]

By default the output goes to ../report/generated/ and every input must come
from artifacts/cluster/ (Vanda runs). Summaries built from local or simulated
runs are refused unless --allow-local is given together with an --out outside
report/generated/; such fragments carry a LOCAL PIPELINE TEST banner in
every caption. Each fragment starts with a comment naming its inputs.

Fragments (written only when the data exist):
Axes for time, problem size and core count are logarithmic (Lecture 12).
  fig_serial_n.tex                                   study "serial_n" (+ the strong serial row)
  fig_strong_runtime.tex, fig_strong_speedup.tex,
  fig_strong_efficiency.tex                          study "strong"
  tab_ranks_threads.tex                              study "ranks_threads" (+ strong rows at the same P)
  tab_schedule.tex                                   study "schedule"
  fig_weak_runtime.tex, fig_weak_efficiency.tex      study "weak" (per T; P0 = smallest P, stated)
  fig_phases.tex                                     strong-study hybrid rows, phase medians
  fig_comm_fraction.tex                              exchange time / wall time, strong and weak
  tab_accuracy_cost.tex                              studies "accuracy" (validate) and "theta"
  fig_gpu_runtime.tex, tab_gpu.tex                   study "gpu_timing" (device and cpu on the same workloads)
  tab_leaf.tex                                       study "leaf" (+ the leaf size 8 row of the same configuration)
  tab_repetitions.tex                                strong runs at their largest N, each repetition against
                                                     serial and (when it was run) hybrid 1x1 of the same repetition
  tab_failed_runs.tex                                every failed, timed-out or skipped run
Runtime figures draw the min-max range of the repetitions as error bars. --context adds the
same sentence (job, node, limits) to every caption. --placement sets the LaTeX float placement
of every fragment (default t). --prefix P (lower-case letters and digits)
writes P_<name>.tex with every \label and \ref renamed fig:P-... and tab:P-..., so the results of
a second job (e.g. the 4-node job on another CPU model) can sit beside the first without
overwriting or merging; without it the output is unchanged.
"""
import argparse
import itertools
import datetime
import json
import math
from pathlib import Path
import re
import sys

CODE = Path(__file__).resolve().parents[1]
REPORT_GEN = CODE.parent / "report/generated"


def esc(s):
    return str(s).replace("\\", "/").replace("_", "\\_").replace("%", "\\%").replace("&", "\\&")


def has_study(row, study):
    return study in (row.get("studies") or "").split(",")


def load(paths):
    rows, failed, inputs = [], [], []
    for p in paths:
        d = json.loads(Path(p).read_text())
        rows += d["rows"]
        failed += d.get("failed", [])
        inputs += d.get("inputs", [str(Path(p).parent)])
    return rows, failed, inputs


class Writer:
    def __init__(self, out, inputs, local, context="", prefix=""):
        self.out, self.inputs, self.local, self.context, self.prefix = out, inputs, local, context, prefix
        self.written = []

    def caption(self, text):
        banner = "\\textbf{LOCAL PIPELINE TEST, NOT A MEASUREMENT.} " if self.local else ""
        return banner + text + (" " + self.context if self.context else "")

    def write(self, name, body):
        stamp = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
        head = (f"% Generated by code/scripts/report_figures.py at {stamp}; do not edit.\n"
                f"% Inputs: {', '.join(self.inputs)}\n")
        if self.prefix:
            name = f"{self.prefix}_{name}"
            body = re.sub(r"\\(label|ref)\{(fig|tab):", lambda m: f"\\{m.group(1)}{{{m.group(2)}:{self.prefix}-", body)
        (self.out / name).write_text(head + body)
        self.written.append(name)


def spread(r, x):
    """Point with the min-max range of the repetitions."""
    return (x, r["wall_median_s"], r["wall_min_s"], r["wall_max_s"])


BARS = " Bars: fastest to slowest repetition."

# Float placement of every fragment; --placement changes it.
PLACEMENT = "t"


def label(r):
    return f"{r['ranks']}$\\times${r['threads']}"


# Distinct marks, so series stay apart in greyscale.
MARKS = ("*", "square*", "triangle*", "diamond*", "pentagon*")


def log_ticks(series):
    """Ticks a reader can name: 1, 2, 5 steps over a narrow range, decades over a wide one."""
    ys = [v for _, pts in series for p in pts for v in p[1:] if v > 0]
    lo, hi = math.floor(math.log10(min(ys))), math.ceil(math.log10(max(ys)))
    steps = (1, 2, 5) if hi - lo <= 2 else (1,)
    return ",".join(f"{m * 10 ** e:g}" for e in range(lo, hi + 1) for m in steps)


def fig_xy(series, xlabel, ylabel, caption, lab, ideal=None, logx=True, logy=False, legend="north west",
           log_base_x=2, axis_opts=""):
    lines = [f"\\begin{{figure}}[{PLACEMENT}]", "\\centering", "\\begin{tikzpicture}",
             "\\begin{axis}[width=0.9\\columnwidth, height=0.65\\columnwidth, "
             f"xlabel={{{xlabel}}}, ylabel={{{ylabel}}}, "
             + (f"xmode=log, log basis x={log_base_x}, " if logx else "")
             + ("log ticks with fixed point, " if logx or logy else "")
             + (f"ymode=log, ytick={{{log_ticks(series)}}}, " if logy and "ytick" not in axis_opts else "")
             + ("ymode=log, " if logy and "ytick" in axis_opts else "")
             + axis_opts
             # Below the plot, so the legend never covers data; legend="inside" keeps the old placement.
             + ("legend style={at={(0.5,-0.32)}, anchor=north, legend columns=2, font=\\footnotesize}, "
                if legend != "inside" else "legend pos=north west, ")
             + "legend cell align=left, grid=major, grid style={gray!25}]"]
    for (name, pts), mark in zip(series, itertools.cycle(MARKS)):
        # A point (x, y, lo, hi) draws lo..hi as an error bar.
        bars = any(len(p) == 4 for p in pts)
        coords = " ".join(f"({p[0]:g},{p[1]:.4g})" + (f" += (0,{p[3] - p[1]:.4g}) -= (0,{p[1] - p[2]:.4g})"
                                                       if len(p) == 4 else "") for p in pts)
        opts = f"mark={mark}, thick" + (", error bars/.cd, y dir=both, y explicit" if bars else "")
        lines.append(f"\\addplot+[{opts}] coordinates {{{coords}}};")
        lines.append(f"\\addlegendentry{{{esc(name)}}}")
    if ideal:
        coords = " ".join(f"({x:g},{y:g})" for x, y in ideal)
        lines.append(f"\\addplot[black, dashed] coordinates {{{coords}}};")
        lines.append("\\addlegendentry{ideal}")
    lines += ["\\end{axis}", "\\end{tikzpicture}", f"\\caption{{{caption}}}", f"\\label{{{lab}}}",
              "\\end{figure}", ""]
    return "\n".join(lines)


def strong(rows, w):
    pts = [r for r in rows if has_study(r, "strong") and "speedup_vs_serial" in r]
    if not pts:
        return
    by_t = {}
    for r in pts:
        by_t.setdefault(r["threads"], []).append(r)
    series_t, series_s, series_e = [], [], []
    for t, rs in sorted(by_t.items()):
        rs.sort(key=lambda r: r["cores"])
        name = "MPI only ($T=1$)" if t == 1 else f"$T={t}$ threads per rank"
        series_t.append((name, [spread(r, r["cores"]) for r in rs]))
        series_s.append((name, [(r["cores"], r["speedup_vs_serial"]) for r in rs]))
        series_e.append((name, [(r["cores"], r["efficiency"]) for r in rs]))
    pmax = max(r["cores"] for r in pts)
    n = sorted({r["n"] for r in pts})
    base = (f"$N={', '.join(fmt_n(x).strip('$') for x in n)}$, median of repetitions; serial Barnes--Hut baseline on the same "
            "CPU model and build.")
    w.write("fig_strong_runtime.tex", fig_xy(
        series_t, "allocated cores $P$", "timed-region wall time (s)", w.caption("Strong-scaling runtime. " + base + BARS),
        "fig:strong-runtime", logy=True, legend="north east"))
    w.write("fig_strong_speedup.tex", fig_xy(
        series_s, "allocated cores $P$", "speedup $S(P)$", w.caption("Strong-scaling speedup. " + base),
        "fig:strong-speedup", ideal=[(1, 1), (pmax, pmax)], logy=True))
    w.write("fig_strong_efficiency.tex", fig_xy(
        series_e, "allocated cores $P$", "efficiency $E(P)$", w.caption("Strong-scaling efficiency. " + base),
        "fig:strong-efficiency", ideal=[(1, 1), (pmax, 1)], legend="south west"))


def table(name, w, caption, lab, head, body, cols=None, wide=False, colsep=None):
    """Single-column tables are set at their natural size and shrunk only if
    wider than the column, so tables share one font size; wide=True gives a
    full-width table* (cols then sets the column types, e.g. a p{} column).
    colsep narrows the gaps, in pt, when a table has many columns."""
    env = "table*" if wide else "table"
    cols = cols or "l" + "r" * (len(head) - 1)
    tab = (["\\begin{tabular}{" + cols + "}", "\\toprule", " & ".join(head) + " \\\\", "\\midrule"]
           + [" & ".join(row) + " \\\\" for row in body] + ["\\bottomrule", "\\end{tabular}"])
    if not wide:
        tab = (["\\sbox0{%"] + tab + ["}%"]
               + ["\\ifdim\\wd0>\\columnwidth\\resizebox{\\columnwidth}{!}{\\usebox0}\\else\\usebox0\\fi"])
    if colsep:
        tab = [f"\\setlength{{\\tabcolsep}}{{{colsep}pt}}"] + tab
    lines = [f"\\begin{{{env}}}[{PLACEMENT}]", "\\centering", "\\small", f"\\caption{{{caption}}}",
             f"\\label{{{lab}}}"] + tab + [f"\\end{{{env}}}", ""]
    w.write(name, "\n".join(lines))


def fmt_wall(r):
    return f"{r['wall_median_s']:.3f} [{r['wall_min_s']:.3f}, {r['wall_max_s']:.3f}]"


def ranks_threads(rows, w):
    rt = [r for r in rows if has_study(r, "ranks_threads")]
    if not rt:
        return
    ps = {r["cores"] for r in rt}
    rs = [r for r in rows if r["program"] == "bh_hybrid" and r["cores"] in ps
          and (has_study(r, "ranks_threads") or has_study(r, "strong"))
          and r["schedule"] == "dynamic"]
    rs.sort(key=lambda r: (r["cores"], -r["ranks"]))
    body = [[str(r["cores"]), label(r), fmt_wall(r),
             f"{r['speedup_vs_serial']:.2f}" if "speedup_vs_serial" in r else "--",
             f"{r['efficiency']:.2f}" if "efficiency" in r else "--",
             f"{r['traverse_imbalance']:.3f}" if "traverse_imbalance" in r else "--"] for r in rs]
    table("tab_ranks_threads.tex", w,
          w.caption("Ranks $\\times$ threads ($R\\times T$) at fixed allocated cores $P$: timed-region wall "
                    "time, median [min, max] in seconds; speedup $S$ and efficiency $E$ against serial "
                    "Barnes--Hut; traversal imbalance (max/mean over ranks)."),
          "tab:ranks-threads", ["$P$", "$R\\times T$", "wall (s)", "$S$", "$E$", "imbalance"], body, colsep=4)


def schedule(rows, w):
    rs = [r for r in rows if has_study(r, "schedule") or
          (r["program"] == "bh_hybrid" and r["ranks"] * r["threads"] == r["cores"] and any(
              has_study(x, "schedule") and x["ranks"] == r["ranks"] and x["threads"] == r["threads"]
              and x["n"] == r["n"] for x in rows))]
    if not any(has_study(r, "schedule") for r in rs):
        return
    sched = [x for x in rows if has_study(x, "schedule")]
    rs = [r for r in rs if has_study(r, "schedule") or any(
        (x["ranks"], x["threads"], x["n"], x["theta"], x["leaf_size"])
        == (r["ranks"], r["threads"], r["n"], r["theta"], r["leaf_size"]) for x in sched)]
    rs = sorted({id(r): r for r in rs}.values(), key=lambda r: (r["cores"], r["ranks"], r["schedule"], r["chunk"]))
    body = [[label(r), esc(r["schedule"]), str(r["chunk"]), fmt_wall(r),
             f"{r['traverse_imbalance']:.3f}" if "traverse_imbalance" in r else "--"] for r in rs]
    table("tab_schedule.tex", w,
          w.caption("OpenMP loop schedule and chunk size (chunk 0 = runtime default): timed-region wall "
                    "time, median [min, max] in seconds, and traversal imbalance."),
          "tab:schedule", ["$R\\times T$", "schedule", "chunk", "wall (s)", "imbalance"], body, colsep=4)


def serial_n(rows, w):
    rs = [r for r in rows if r["program"] == "bh_serial"
          and (has_study(r, "serial_n") or has_study(r, "strong"))]
    if len({r["n"] for r in rs}) < 2:
        return
    if len({(r["theta"], r["leaf_size"], r["steps"], r["cpu_model"]) for r in rs}) > 1:
        sys.exit("serial_n: rows differ in theta, leaf size, steps or CPU model; split the input")
    rs.sort(key=lambda r: r["n"])
    xs = [math.log(r["n"]) for r in rs]
    ys = [math.log(r["wall_median_s"]) for r in rs]
    mx, my = sum(xs) / len(xs), sum(ys) / len(ys)
    slope = sum((x - mx) * (y - my) for x, y in zip(xs, ys)) / sum((x - mx) ** 2 for x in xs)
    r0 = rs[0]
    w.write("fig_serial_n.tex", fig_xy(
        [("serial Barnes--Hut", [spread(r, r["n"]) for r in rs])],
        "particles $N$", "timed-region wall time (s)",
        w.caption(f"Serial runtime against problem size, $\\theta={r0['theta']:g}$, leaf size {r0['leaf_size']}, "
                  f"{r0['steps']} timed steps, median of repetitions. Least-squares slope on the log--log axes: "
                  f"{slope:.3f}." + BARS), "fig:serial-n", logy=True, log_base_x=10))


def weak(rows, w):
    by_t = {}
    for r in rows:
        if has_study(r, "weak"):
            by_t.setdefault(r["threads"], []).append(r)
    by_t = {t: sorted(rs, key=lambda r: r["cores"]) for t, rs in by_t.items() if len(rs) >= 2}
    if not by_t:
        return
    name = lambda t: "MPI only ($T=1$)" if t == 1 else f"$T={t}$ threads per rank"
    runtime, eff, ends, notes = [], [], set(), []
    for t, rs in sorted(by_t.items()):
        p0 = rs[0]
        runtime.append((name(t), [spread(r, r["cores"]) for r in rs]))
        eff.append((name(t), [(r["cores"], p0["wall_median_s"] / r["wall_median_s"]) for r in rs]))
        ends |= {p0["cores"], rs[-1]["cores"]}
        per_core = sorted({r["n"] // r["cores"] for r in rs})
        notes.append(f"$T={t}$: $P_0={p0['cores']}$, $N_0={fmt_int(p0['n'])}$, "
                     f"{', '.join(fmt_int(x) for x in per_core)} particles per core")
    base = "; ".join(notes) + ". Constant particles per core is not constant work per core."
    w.write("fig_weak_runtime.tex", fig_xy(
        runtime, "allocated cores $P$", "timed-region wall time (s)",
        w.caption("Weak-scaling runtime. " + base + BARS), "fig:weak-runtime", logy=True))
    w.write("fig_weak_efficiency.tex", fig_xy(
        eff, "allocated cores $P$", "$T(P_0,N_0)/T(P,N)$", w.caption("Weak-scaling efficiency. " + base),
        "fig:weak", ideal=[(min(ends), 1), (max(ends), 1)], legend="south west"))


def phases(rows, w):
    rs = [r for r in rows if has_study(r, "strong") and r["program"] == "bh_hybrid"]
    if not rs:
        return
    t = min(r["threads"] for r in rs)
    rs = sorted((r for r in rs if r["threads"] == t), key=lambda r: r["cores"])
    names = [("integrate_median_s", "integrate"), ("exchange_median_s", "exchange"),
             ("build_median_s", "tree build"), ("traverse_median_s", "traversal")]
    # A phase measured as exactly zero (no exchange on one rank) cannot sit on a log axis.
    series = [(nm, [(r["cores"], r[key]) for r in rs if r[key] > 0]) for key, nm in names]
    w.write("fig_phases.tex", fig_xy(
        [s for s in series if s[1]], "allocated cores $P$", "median phase time (s)",
        w.caption(f"Phase times of the strong-scaling runs with $T={t}$. Each phase is the maximum over ranks, "
                  "so the phases need not sum to the wall time; zero values are omitted from the log axis."),
        "fig:phases", logy=True, legend="south west"))


def comm_fraction(rows, w):
    series = []
    for study in ("strong", "weak"):
        by_t = {}
        for r in rows:
            if has_study(r, study) and r["program"] == "bh_hybrid":
                by_t.setdefault(r["threads"], []).append(r)
        for t, rs in sorted(by_t.items()):
            rs.sort(key=lambda r: r["cores"])
            series.append((f"{study}, $T={t}$", [(r["cores"], r["exchange_median_s"] / r["wall_median_s"]) for r in rs]))
    if series:
        w.write("fig_comm_fraction.tex", fig_xy(
            series, "allocated cores $P$", "exchange time / wall time",
            w.caption("Share of the timed region spent in the per-step position exchange "
                      "(\\texttt{MPI\\_Allgatherv}), maximum over ranks divided by wall time."),
            "fig:comm-fraction",
            axis_opts="scaled y ticks=false, yticklabel style={/pgf/number format/fixed, /pgf/number format/precision=2}, "))


def accuracy(rows, inputs, w):
    acc = {}
    for d in inputs:
        for f in sorted(Path(d).glob("validate/*.txt")):
            for line in f.read_text().splitlines():
                m = re.search(r"validate n=(\d+) theta=([\d.]+) .*max_rel_err=(\S+) mean_rel_err=(\S+)", line)
                if m:
                    acc[float(m.group(2))] = (int(m.group(1)), m.group(3), m.group(4))
    cost = {r["theta"]: r for r in rows if r["program"] == "bh_hybrid"
            and (has_study(r, "theta") or has_study(r, "theta_cost"))}
    if cost:
        # The default theta is measured by another study at the same configuration.
        c0 = next(iter(cost.values()))
        for r in rows:
            if (r["program"] == "bh_hybrid" and r["theta"] not in cost and r["schedule"] == c0["schedule"]
                    and (r["ranks"], r["threads"], r["n"], r["leaf_size"], r["chunk"])
                    == (c0["ranks"], c0["threads"], c0["n"], c0["leaf_size"], c0["chunk"])):
                cost[r["theta"]] = r
    if not acc and not cost:
        return
    thetas = sorted(set(acc) | set(cost))
    # Settings shared by every row go into the caption; a column is kept only where rows differ.
    err_n = {a[0] for a in acc.values()}
    cfg = {(label(c), c["n"]) for c in cost.values()}
    one_n, one_cfg = len(err_n) == 1, len(cfg) == 1
    head = (["$\\theta$"] + ([] if one_n else ["$N$ (error)"]) + ["max rel. error", "mean rel. error"]
            + ([] if one_cfg else ["$R\\times T$"]) + ["wall (s)"])
    body = []
    for th in thetas:
        a = acc.get(th)
        c = cost.get(th)
        body.append([f"{th:g}"] + ([] if one_n else [f"{a[0]}" if a else "--"])
                    + [fmt_sci(a[1]) if a else "--", fmt_sci(a[2]) if a else "--"]
                    + ([] if one_cfg else [label(c) if c else "--"]) + [fmt_wall(c) if c else "--"])
    where = ""
    if one_n:
        where += f" Errors at $N={next(iter(err_n))}$."
    if one_cfg:
        lab, n = next(iter(cfg))
        where += f" Times at {lab}, $N={fmt_n(n).strip('$')}$."
    table("tab_accuracy_cost.tex", w,
          w.caption("Accuracy against cost across $\\theta$: force error of serial Barnes--Hut against direct "
                    "summation, and hybrid timed-region wall time, median [min, max] in seconds." + where),
          "tab:accuracy-cost", head, body, colsep=4)


def leaf(rows, w):
    lf = [r for r in rows if has_study(r, "leaf")]
    if not lf:
        return
    keys = {(r["program"], r["ranks"], r["threads"], r["n"], r["theta"], r["schedule"], r["chunk"]) for r in lf}
    rs = [r for r in rows if (r["program"], r["ranks"], r["threads"], r["n"], r["theta"], r["schedule"], r["chunk"]) in keys
          and (has_study(r, "leaf") or r["leaf_size"] == 8)]
    rs = sorted({id(r): r for r in rs}.values(), key=lambda r: (r["program"], r["cores"], r["leaf_size"]))
    ref = {(r["program"], r["ranks"], r["threads"]): r["wall_median_s"] for r in rs if r["leaf_size"] == 8}
    body = [["serial" if r["program"] == "bh_serial" else label(r), fmt_n(r["n"]), str(r["leaf_size"]), fmt_wall(r),
             f"{r['wall_median_s'] / ref[(r['program'], r['ranks'], r['threads'])]:.2f}"
             if (r["program"], r["ranks"], r["threads"]) in ref else "--"] for r in rs]
    table("tab_leaf.tex", w,
          w.caption("Leaf size $L$: timed-region wall time, median [min, max] in seconds, and the median relative "
                    "to $L=8$ in the same configuration (serial program, or hybrid $R\\times T$)."),
          "tab:leaf", ["run", "$N$", "$L$", "wall (s)", "vs $L=8$"], body, colsep=4)


def repetitions(rows, inputs, w):
    """Each strong-scaling repetition against the serial and, when present, hybrid 1x1 runs of the same repetition.
    Repetitions are interleaved, so runs of one repetition ran close together in time."""
    strong_rows = [r for r in rows if has_study(r, "strong") or has_study(r, "ranks_threads")]
    if not strong_rows:
        return
    n = max(r["n"] for r in strong_rows)
    walls = {}
    for d in inputs:
        for f in Path(d).glob("raw/*.json"):
            rec = json.loads(f.read_text())
            res = rec.get("result") or {}
            study = rec.get("tags", {}).get("study")
            if rec.get("ok") and res.get("n") == n and study in ("strong", "ranks_threads") \
                    and res.get("theta") == 0.5 and res.get("leaf_size") == 8:
                key = ("serial", 1, 1) if res["program"] == "bh_serial" else ("hybrid", res["ranks"], res["threads"])
                if key[0] == "hybrid" and res.get("schedule_effective") != "dynamic":
                    continue
                walls.setdefault(key, {})[rec["rep"]] = res["wall_s"]
    s, one = walls.get(("serial", 1, 1)), walls.get(("hybrid", 1, 1))
    if not s:
        return
    reps = sorted(s)

    def rng(vals):
        if not vals:
            return "--"
        lo, hi = f"{min(vals):.2f}", f"{max(vals):.2f}"
        return lo if lo == hi else f"{lo}--{hi}"

    body = []
    for key in sorted(walls, key=lambda k: (k[1] * k[2], k[0] != "serial", -k[1])):
        p = key[1] * key[2]
        times = walls[key]
        e_s = [s[i] / times[i] / p for i in reps if i in times]
        e_1 = [one[i] / times[i] / p for i in reps if one and i in times and i in one]
        row = [("serial" if key[0] == "serial" else f"{key[1]}$\\times${key[2]}"), str(p),
               ", ".join(f"{times[i]:.2f}" if i in times else "--" for i in reps),
               rng(e_s) if key[0] != "serial" else "--"]
        if one:
            row.append(rng(e_1) if key[0] != "serial" and key != ("hybrid", 1, 1) else "--")
        body.append(row)
    head = (f"Each repetition of the strong-scaling runs at $N={fmt_n(n).strip('$')}$: timed-region wall time, "
            "and efficiency $E$ (smallest to largest over the repetitions) against ")
    if one:
        text = (head + "the serial and the hybrid $1\\times1$ runs of the same repetition. The two columns show "
                "how much the choice of baseline moves the result.")
        cols = ["$R\\times T$", "$P$", "wall per repetition (s)", "$E$ vs serial", "$E$ vs $1\\times1$"]
    else:
        # No hybrid 1x1 run in these inputs: the serial run is the only baseline, so do not name another.
        text = (head + "the serial run of the same repetition, the only baseline these runs include.")
        cols = ["$R\\times T$", "$P$", "wall per repetition (s)", "$E$ vs serial"]
