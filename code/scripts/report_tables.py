#!/usr/bin/env python3
"""Generate the report's validation tables from retained local evidence.

Reads artifacts/local/{serial,hybrid}_validation_linux.json and
energy_study_linux.json and writes LaTeX fragments to ../report/generated/,
which main.tex includes with \\input. No number in these tables is typed by
hand; rerun after the evidence changes:

  python3 scripts/report_tables.py
"""
import json
from pathlib import Path
import re

code = Path(__file__).resolve().parents[1]
evidence = code / "artifacts/local"
out = code.parent / "report/generated"
out.mkdir(parents=True, exist_ok=True)


def sci(x):
    """LaTeX scientific notation, e.g. 1.2\\times10^{-14}; exact zero stays 0."""
    if x == 0:
        return "0"
    m, e = f"{x:.1e}".split("e")
    return f"${m}\\times10^{{{int(e)}}}$"


def tex_escape(text):
    return text.replace("_", "\\_")


def provenance(d):
    srcs = d.get("source_sha256", {})
    short = ", ".join(f"\\texttt{{{tex_escape(Path(k).name)}}} {v[:8]}" for k, v in sorted(srcs.items()))
    return f"{d['timestamp_utc'][:10]}; sources {short}"


# Correctness tables use the newest Vanda correctness run when one exists,
# otherwise the local Docker evidence; captions name whichever was used.
cluster_runs = sorted((code / "artifacts/cluster/runs").glob("correctness-*"))
if cluster_runs:
    run = cluster_runs[-1]
    job = run.name.rsplit("-", 1)[-1]
    serial_path = next(run.glob("serial_validation_*.json"))
    hybrid_path = next(run.glob("hybrid_validation_*.json"))
    env = (run / "env/environment.txt").read_text()
    cpu = next(l.split(":", 1)[1].strip() for l in env.splitlines() if l.startswith("Model name"))
    where = (f"Vanda compute node, PBS job {job} ({cpu.replace('(R)', '')}, "
             "Open MPI~4.1.6, GCC~13.2), 8 allocated cores.")
else:
    serial_path = evidence / "serial_validation_linux.json"
    hybrid_path = evidence / "hybrid_validation_linux.json"
    where = "Local development run (Docker, Open MPI~4.1.4, GCC~12), not cluster evidence."
serial = json.loads(serial_path.read_text())
hybrid = json.loads(hybrid_path.read_text())
energy = json.loads((evidence / "energy_study_linux.json").read_text())

# Approximation error: Barnes-Hut vs direct summation.
rows = []
for m in serial["measurements"]:
    rows.append(f"{m['theta']:.1f} & {m['leaf_size']} & {sci(m['max_rel_err'])} & "
                f"{sci(m['mean_rel_err'])} \\\\")
(out / "approximation_table.tex").write_text(
    "% Generated by code/scripts/report_tables.py from " + str(serial_path.relative_to(code)) + "\n"
    "\\begin{table}[t]\n\\centering\\small\n"
    "\\caption{Approximation error of serial Barnes--Hut against direct summation, "
    f"$N={serial['measurements'][0]['n']}$, seed {serial['measurements'][0]['seed']}, "
    "relative error of the acceleration vector per particle. " + where + "}\n\\label{tab:approx}\n"
    "\\begin{tabular}{rrrr}\n\\hline\n$\\theta$ & leaf & max rel. & mean rel. \\\\\n\\hline\n"
    + "\n".join(rows) + "\n\\hline\n\\end{tabular}\n\\end{table}\n")

# Edge-case self-test cases, by name.
cases = re.findall(r"self_test case=(\S+).*?(PASS|FAIL)", serial["self_test_stdout"])
names = sorted({c for c, _ in cases})
passed = sum(1 for _, s in cases if s == "PASS")
(out / "selftest_summary.tex").write_text(
    "% Generated by code/scripts/report_tables.py\n"
    f"{passed} of {len(cases)} self-test checks passed, covering: "
    + ", ".join(n.replace("_", "\\_") for n in names) + ".\n")

# Implementation error: serial vs hybrid.
rows = []
for c in hybrid["cases"]:
    diffs = [c.get(f"{f}_max_abs_diff") for f in ("pos", "vel", "acc")]
    shown = max(d for d in diffs if d is not None)
    rows.append(f"{c['ranks']}$\\times${c['threads']} & {c['schedule']}/{c['chunk']} & {c['n']} & "
                f"{c['steps']} & {sci(shown)} & {'pass' if c['ok'] else 'FAIL'} \\\\")
def tex_num(x):
    """1e-12 as 10^{-12}, 2.5e-10 as 2.5 x 10^{-10}, for math mode."""
    m, e = f"{x:e}".split("e")
    m = f"{float(m):g}"
    return f"10^{{{int(e)}}}" if m == "1" else f"{m}\\times10^{{{int(e)}}}"


tol = hybrid["tolerances"]
(out / "hybrid_table.tex").write_text(
    "% Generated by code/scripts/report_tables.py from " + str(hybrid_path.relative_to(code)) + "\n"
    "\\begin{table}[t]\n\\centering\\small\n"
    "\\caption{Implementation error: MPI+OpenMP against serial Barnes--Hut at identical settings "
    "($\\theta=0.5$ unless the case tests otherwise), largest absolute difference over positions, "
    "velocities and accelerations by particle ID. Tolerances: one step "
    f"${tex_num(tol['acceleration_1_step'][0])}|a|+{tex_num(tol['acceleration_1_step'][1])}\\max|a|$; ten steps "
    f"${tex_num(tol['trajectory_10_steps'][0])}|x|+{tex_num(tol['trajectory_10_steps'][1])}\\max|x|$. "
    + where + "}\n"
    # Six columns overflowed the two-column layout by 5.5 pt at the default
    # 6 pt column separation; 4 pt fits without shrinking the font.
    "\\label{tab:hybrid}\n\\setlength{\\tabcolsep}{4pt}\n\\begin{tabular}{llrrrl}\n\\hline\n"
    "ranks$\\times$thr. & schedule & $N$ & steps & max diff & \\\\\n\\hline\n"
    + "\n".join(rows) + "\n\\hline\n\\end{tabular}\n\\end{table}\n")
(out / "hybrid_extras.tex").write_text(
    "% Generated by code/scripts/report_tables.py\n"
    f"Three repeated runs with 2 ranks $\\times$ 4 threads and dynamic chunk 1 were "
    f"{'bitwise identical' if hybrid['repeat_bitwise_identical'] else 'NOT identical'}; "
    f"a $10^{{-9}}$ relative perturbation of one position was "
    f"{'detected' if hybrid['negative_control_detected'] else 'NOT detected'} by the comparator; "
    f"evidence recorded {provenance(hybrid)}.\n")

# Two-node comparison: the newest twonode run that reached the hybrid gate. The
# prose in main.tex keeps the unbound comparison apart from the bound checks.
twonode_runs = sorted(r for r in (code / "artifacts/cluster/runs").glob("twonode-*")
                      if list(r.glob("hybrid_validation_*.json")))
if twonode_runs:
    run = twonode_runs[-1]
    job = run.name.rsplit("-", 1)[-1]
    tn = json.loads(next(run.glob("hybrid_validation_*.json")).read_text())
    gates = [l.split() for l in (run / "gates.txt").read_text().splitlines() if l.strip()]
    counted = [g for g in gates if "kind=optional" not in g]
    passed = sum(g[1] == "PASS" for g in counted)
    probes = [g for g in counted if g[0].startswith("place_")]
    spanning = sum(len(set(c["hosts"])) == 2 for c in tn["cases"])
    hosts = sorted({h for c in tn["cases"] for h in c["hosts"]})
    biggest = max(max(c.get(f"{f}_max_abs_diff") or 0 for f in ("pos", "vel", "acc")) for c in tn["cases"])
    alloc = (run / "gate_allocation.log").read_text()
    model = re.search(r"models=\['([^']+)'\]", alloc).group(1).replace("_", " ").replace("(R)", "")
    rev = re.search(r"^SOURCE_GIT_REV=(\w{7})", (run / "env/environment.txt").read_text(), re.M).group(1)
    binding = "with binding off (\\texttt{-{}-bind-to none})" if "--bind-to none" in tn["mpirun_flags"] else "with binding on"
    (out / "twonode_note.tex").write_text(
        "% Generated by code/scripts/report_tables.py from " + run.name + "\n"
        f"PBS job {job} (commit \\texttt{{{rev}}}; nodes {' and '.join(hosts)}, both {model}; 8 allocated cores each) "
        f"passed {passed} of {len(counted)} critical and required steps. In its hybrid--serial step, "
        f"{sum(c['ok'] for c in tn['cases'])} of {len(tn['cases'])} cases were within tolerance, and the largest "
        f"difference was {sci(biggest)}. {spanning} of the cases ran across both nodes, with up to "
        f"{max(c['ranks'] for c in tn['cases'])} ranks and $N={max(c['n'] for c in tn['cases'])}$, all {binding}. "
        f"{sum(g[1] == 'PASS' for g in probes)} of {len(probes)} bound placement probes passed.\n")

# GPU test: the newest GPU validation run. Only a run on a device gets a note.
gpu_runs = sorted((code / "artifacts/cluster/runs").glob("gpu_validate-*"))
if gpu_runs:
    run = gpu_runs[-1]
    job = run.name.rsplit("-", 1)[-1]
    g = json.loads(next(run.glob("gpu_validation_*.json")).read_text())
    if g["real_gpu_executed"] and g["device_probe"]["kernel_on_device"] == 1 and g["device_probe"]["separate_memory"] == 1:
        env = (run / "env/environment.txt").read_text()
        gpu_name = re.search(r"^GPU 0: (.+?) \(UUID", env, re.M).group(1)
        compiler = re.search(r"^nvc\+\+ (\S+)", env, re.M).group(1)
        details = {c["name"]: c.get("detail", "") for c in g["checks"]}
        traj = float(re.search(r"difference (\S+),", details["trajectory device against serial"]).group(1))
        theta0 = float(re.search(r"max_rel_err_vs_direct=(\S+)", details["validate device theta=0.0 leaf=8"]).group(1))
        util = [int(l.split(",")[2]) for l in (run / "gpu_samples.csv").read_text().splitlines() if l.strip()]
        (out / "gpu_note.tex").write_text(
            "% Generated by code/scripts/report_tables.py from " + run.name + "\n"
            f"PBS job {job} (commit \\texttt{{{g['source_git_rev'][:7]}}}, {gpu_name}, \\texttt{{nvc++}} {compiler}) "
            f"passed {sum(c['ok'] for c in g['checks'])} of {len(g['checks'])} checks. At $\\theta=0$ the device "
            f"force differed from direct summation by at most {sci(theta0)} (relative), and a 20-step trajectory "
            f"differed from the serial program by at most {sci(traj)}. While a run of $N=10^6$ had offload set to "
            f"mandatory, \\texttt{{nvidia-smi}} reported up to {max(util)}\\% GPU utilisation and listed the "
            "program as a process on the GPU.\n")

# Energy drift by theta and dt.
dts = sorted({r["dt"] for r in energy["rows"]}, reverse=True)
thetas = sorted({r["theta"] for r in energy["rows"]})
lookup = {(r["theta"], r["dt"]): r["energy_rel_drift"] for r in energy["rows"]}
rows = [f"{t:.1f} & " + " & ".join(sci(lookup[(t, dt)]) for dt in dts) + " \\\\" for t in thetas]
(out / "energy_table.tex").write_text(
    "% Generated by code/scripts/report_tables.py from energy_study_linux.json\n"
    "\\begin{table*}[t]\n\\centering\\small\n"
    "\\caption{Relative change in total energy over simulated time "
    f"$T={energy['simulated_time']}$ ($N={energy['n']}$, leaf size {energy['leaf_size']}). "
    "Energy is evaluated exactly ($O(N^2)$), outside any timed region. Local development run, "
    "supplementary diagnostic only.}\n\\label{tab:energy}\n"
    "\\begin{tabular}{r" + "r" * len(dts) + "}\n\\hline\n$\\theta$ & "
    + " & ".join(f"$\\Delta t={dt:g}$" for dt in dts) + " \\\\\n\\hline\n"
    + "\n".join(rows) + "\n\\hline\n\\end{tabular}\n\\end{table*}\n")

print(f"wrote {', '.join(sorted(p.name for p in out.glob('*.tex')))} to {out}")

# Process-binding observation from the latest local binding run.
binding_runs = sorted((evidence / "runs").glob("binding-*/summary.json"))
if binding_runs:
    b = json.loads(binding_runs[-1].read_text())
    by_launcher = {r["launcher"]: r for r in b["rows"]}
    bound = next(r for k, r in by_launcher.items() if "--bind-to none" not in k)
    free = next(r for k, r in by_launcher.items() if "--bind-to none" in k)
    (out / "binding_note.tex").write_text(
        "% Generated by code/scripts/report_tables.py from " + binding_runs[-1].parent.name + "\n"
        f"With one rank and {free['threads']} OpenMP threads ($N={free['n']}$, {free['steps']} timed steps, "
        f"{free['reps']} repetitions each, local Docker container), Open MPI's default placement gave a median "
        f"timed region of {bound['wall_median_s']:.2f}\\,s against {free['wall_median_s']:.2f}\\,s with "
        "\\texttt{-{}-bind-to none}. Open MPI's \\texttt{-{}-report-bindings} showed the default binding the "
        "rank, and therefore its whole thread team, to a single hardware thread.\n")

# Serial leaf-size sweep from the latest local sweep.
leaf_runs = sorted((evidence / "runs").glob("leafsweep-*/summary.json"))
if leaf_runs:
    rows = sorted(json.loads(leaf_runs[-1].read_text())["rows"], key=lambda r: r["leaf_size"])
    parts = [f"$L={r['leaf_size']}$: {r['wall_median_s']:.2f}\\,s [{r['wall_min_s']:.2f}, {r['wall_max_s']:.2f}]"
             for r in rows]
    best = min(rows, key=lambda r: r["wall_median_s"])
    one = next(r for r in rows if r["leaf_size"] == 1)
    k = rows.index(best)
    overlapping = [r["leaf_size"] for r in rows[max(0, k - 1):k + 2] if r is not best
                   and r["wall_min_s"] <= best["wall_max_s"] and best["wall_min_s"] <= r["wall_max_s"]]
    overlap_text = (", and its range overlapped that of " + " and ".join(f"$L={x}$" for x in overlapping)
                    if overlapping else ", and its range did not overlap its neighbours'")
    (out / "leaf_note.tex").write_text(
        "% Generated by code/scripts/report_tables.py from " + leaf_runs[-1].parent.name + "\n"
        f"In a local serial sweep ($N={rows[0]['n']}$, {rows[0]['steps']} timed steps, median [min, max] of "
        f"{rows[0]['reps']} runs, Docker container) the timed region took " + "; ".join(parts) +
        f". The lowest median, $L={best['leaf_size']}$, was {100 * (1 - best['wall_median_s'] / one['wall_median_s']):.0f}\\,\\% "
        "below single-particle leaves" + overlap_text + ".\n")
